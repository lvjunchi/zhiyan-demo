    const stats = page.getByRole('region', { name: '文档导入统计' })
    await expect(stats.getByLabel('待澄清问题', { exact: true })).toHaveText('待澄清问题0')
    await input.setInputFiles('../演示导入文件/综合演示/01_综合技术协议_V1.docx')
    await expect(stats.getByRole('img', { name: '文件状态：已解析1份，已归档待解析0份，未归档待核对1份，已解析需核对0份' })).toBeVisible()
    await stats.screenshot({ path: `${evidence}/demo-import-two-files.png`, style: '.platform-masthead {visibility:hidden;}' })
    await page.getByRole('button', { name: '取消待核对', exact: true }).click()
    await openWorkspaceTab(page, '需求清单')
    const requirements = await (await request.get(`/api/projects/${pid}/requirements`)).json() as Requirement[]
    expect(requirements).toHaveLength(19)
    const req = requirements.find(item => item.parameter_name.includes('最大功率'))!
    const row = page.getByRole('row').filter({ has: page.getByRole('cell', { name: req.display_code, exact: true }) })
    expect(await row.locator('.requirement-row-actions button').last().innerText()).toBe('审核记录')
    await row.getByRole('button', { name: `驳回 ${req.display_code}`, exact: true }).click()
    await expect(page.getByLabel('驳回原因')).not.toHaveAttribute('required')
    await page.getByRole('button', { name: '提交驳回', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await page.getByRole('button', { name: /^已驳回 \d+ 条$/ }).click()
    await expect(row.getByText('已驳回', { exact: true })).toBeVisible()
    for (const item of requirements.filter(item => item.id !== req.id)) {
      await post(`/api/requirements/${item.id}/confirmations`, { ...actor, expected_revision: item.current_revision, decision: 'confirmed' })
    }
    await post(`/api/projects/${pid}/variant-analysis`, { base_display_code: 'JX-12A' })
