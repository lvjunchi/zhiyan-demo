import { expect, test } from '@playwright/test'
import { openWorkspaceTab } from '../e2e-support/navigation'
const evidence = process.env.ZHIYAN_EVIDENCE_DIR ?? 'test-results/overview/screenshots'

test('clears only after confirmation, downloads the pre-clear backup and imports Word again', async ({ page, request }) => {
  await page.goto('/')
  const projects = await (await request.get('/api/projects')).json() as { id: string; display_code: string }[]
  const project = projects[0]
  const before = await (await request.get('/api/system/backup')).json()
  await openWorkspaceTab(page, '系统设置')
  const trigger = page.getByRole('button', { name: '清空当前项目业务数据', exact: true })
  await trigger.click()
  let dialog = page.getByRole('dialog', { name: '清空当前项目业务数据' })
  await expect(dialog.getByLabel('输入项目编号确认')).toBeVisible()
  await expect(dialog.getByRole('button', { name: '备份并清空当前项目' })).toBeDisabled()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const mobileSubmit = await dialog.getByRole('button', { name: '备份并清空当前项目' }).boundingBox()
  expect(mobileSubmit).not.toBeNull()
  expect(mobileSubmit!.y + mobileSubmit!.height).toBeLessThanOrEqual(844)
  await page.screenshot({ path: `${evidence}/clear-confirmation-mobile.png`, fullPage: true })
  await page.setViewportSize({ width: 1440, height: 900 })
  await dialog.getByRole('button', { name: '取消清空' }).click()
  expect((await (await request.get('/api/system/backup')).json()).sha256).toBe(before.sha256)
  await trigger.click()
  dialog = page.getByRole('dialog', { name: '清空当前项目业务数据' })
  await dialog.getByLabel('输入项目编号确认').fill(project.display_code)
  const submitBounds = await dialog.getByRole('button', { name: '备份并清空当前项目' }).boundingBox()
  expect(submitBounds).not.toBeNull()
  expect(submitBounds!.y + submitBounds!.height).toBeLessThanOrEqual(page.viewportSize()!.height)
  await page.screenshot({ path: `${evidence}/clear-confirmation.png`, fullPage: true })
  await dialog.getByRole('button', { name: '备份并清空当前项目' }).click()
  const backupLink = page.getByRole('link', { name: '下载清空前完整备份' })
  await expect(backupLink).toBeVisible()
  const backup = await (await request.get((await backupLink.getAttribute('href'))!)).json()
  expect(backup.sha256).toBe(before.sha256)
  const after = await (await request.get('/api/system/backup')).json()
  expect(after.counts.requirements).toBe(0)
  expect(after.counts.product_bases).toBe(before.counts.product_bases)
  expect(after.counts.base_parts).toBe(before.counts.base_parts)
  await page.getByRole('button', { name: '重新载入空白项目' }).click()
  await openWorkspaceTab(page, '项目总览')
  await expect(page.getByRole('region', { name: '项目启动介绍' })).toBeVisible()
  await page.getByRole('button', { name: '开始导入技术协议' }).click()
  await page.getByLabel('选择协议文件').setInputFiles('../演示导入文件/01_重型变速器技术协议_V1.docx')
  const stats = page.getByRole('region', { name: '文档导入统计' })
  await expect(stats.getByLabel('待核对文档')).toContainText('1')
  await expect(page.getByRole('region', { name: '协议处理进度' })).toContainText('文本已就绪')
  await page.getByRole('button', { name: '导入并解析', exact: true }).click()
  await expect(page.getByRole('region', { name: '协议处理进度' })).toContainText('结果已保存，需求仍需人工审核')
  const requirements = await (await request.get(`/api/projects/${project.id}/requirements`)).json() as { review_status: string }[]
  expect(requirements.length).toBeGreaterThan(0)
  expect(requirements.every(row => row.review_status === 'draft')).toBe(true)
  await expect(stats.getByLabel('待审核需求')).toContainText(String(requirements.length))
  const viewResult = page.getByRole('button', { name: '查看解析结果', exact: true })
  await viewResult.click()
  const resultDialog = page.getByRole('dialog', { name: '文档解析结果' })
  await expect(resultDialog.getByText(/已完成解析/)).toBeVisible()
  await resultDialog.getByRole('button', { name: '关闭解析结果' }).click()
  await expect(viewResult).toBeFocused()
  await expect(page.getByRole('heading', { name: '解析结果', exact: true })).toHaveCount(0)
  const workspace = await (await request.get(`/api/projects/${project.id}/workspace`)).json()
  const parsingStage = workspace.stages.find((stage: { key: string }) => stage.key === 'parsing')
  for (const note of parsingStage.notes) await expect(page.getByRole('region', { name: '当前模块工作提示' })).toContainText(note)
  await page.screenshot({ path: `${evidence}/document-status-desktop.png`, fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `${evidence}/document-status-mobile.png`, fullPage: true })
})

test('PDF extraction failures persist, successful previews can be cancelled, and unrecognised text needs review', async ({ page, request }) => {
  await page.goto('/')
  await openWorkspaceTab(page, '协议解析与澄清')
  await page.getByLabel('选择协议文件').setInputFiles({ name: 'broken.pdf', mimeType: 'application/pdf', buffer: Buffer.from('broken pdf') })
  await expect(page.getByRole('region', { name: '协议处理进度' })).toContainText('文本提取失败')
  await expect(page.getByRole('region', { name: '文档导入统计' }).getByLabel('处理失败')).toContainText('1')
  await page.reload()
  await openWorkspaceTab(page, '协议解析与澄清')
  await expect(page.getByRole('region', { name: '文档导入统计' }).getByLabel('处理失败')).toContainText('1')
  await page.getByLabel('选择协议文件').setInputFiles('../docs/test-evidence/2026-10-23/STAGE-03/text-test.pdf')
  await expect(page.getByLabel('来源文档正文')).toContainText('PDF 第 1 页')
  await page.getByLabel('来源文档编号').fill('DOC-PDF-01')
  await page.getByRole('button', { name: '导入并解析', exact: true }).click()
  await expect(page.getByRole('region', { name: '协议处理进度' })).toContainText('结果已保存')
  const row = page.getByRole('row').filter({ hasText: 'DOC-PDF-01' })
  await expect(row).toContainText('已解析 · 需人工核对')
  await expect(row).toContainText('0 / 0')
  await page.getByLabel('选择协议文件').setInputFiles('../docs/test-evidence/2026-10-23/STAGE-03/text-test.pdf')
  const stats = page.getByRole('region', { name: '文档导入统计' })
  await expect(stats.getByLabel('待核对文档')).toContainText('2')
  await page.getByRole('button', { name: '取消待核对', exact: true }).click()
  await expect(stats.getByLabel('待核对文档')).toContainText('1')
  await expect(page.getByText('已取消核对', { exact: true })).toBeVisible()
  const project = (await (await request.get('/api/projects')).json())[0]
  const attempts = await (await request.get(`/api/projects/${project.id}/document-imports`)).json() as { status: string }[]
  expect(attempts.some(item => item.status === 'cancelled')).toBe(true)
  expect(attempts.some(item => item.status === 'failed')).toBe(true)
  await page.screenshot({ path: `${evidence}/pdf-review-and-failure.png`, fullPage: true })
})
