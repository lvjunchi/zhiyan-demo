import { openWorkspaceTab } from '../e2e-support/navigation'
import { expect, test } from '@playwright/test'

const evidence = process.env.ZHIYAN_EVIDENCE_DIR ?? 'test-results/screenshots'

test('requirement drawer keeps filters, focus and viewport boundaries', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await openWorkspaceTab(page, '需求清单')
  await page.getByRole('button', { name: /^全部需求 \d+ 条$/ }).click()
  await page.getByLabel('搜索需求').fill('发动机最大扭矩')
  const trigger = page.getByRole('button', { name: '查看 REQ-P01-B-003 来源与版本', exact: true })
  await trigger.click()
  const drawer = page.getByRole('dialog', { name: '需求来源与版本对比', exact: true })
  await expect(drawer.getByLabel('对比前版本')).toBeVisible()
  expect(await drawer.evaluate(element => element.matches(':modal'))).toBe(true)
  const bounds = await drawer.boundingBox()
  expect(bounds!.x + bounds!.width).toBe(1440)
  expect(bounds!.height).toBe(900)
  await expect(drawer.getByRole('button', { name: '关闭详情' })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  expect(await drawer.evaluate(element => element.contains(document.activeElement))).toBe(true)
  await page.screenshot({ path: `${evidence}/requirement-drawer-desktop.png` })
  await page.keyboard.press('Escape')
  await expect(drawer).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await expect(page.getByLabel('搜索需求')).toHaveValue('发动机最大扭矩')
  await page.setViewportSize({ width: 390, height: 844 })
  await trigger.click()
  await expect(drawer.getByLabel('对比前版本')).toBeVisible()
  expect(await drawer.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  const mobile = await drawer.boundingBox()
  expect(mobile!.x).toBeGreaterThanOrEqual(0)
  expect(mobile!.x + mobile!.width).toBeLessThanOrEqual(390)
  await page.screenshot({ path: `${evidence}/requirement-drawer-mobile.png` })
  await drawer.getByRole('button', { name: '关闭详情' }).click()
  await expect(trigger).toBeFocused()
})

test('sample comparison opens wide, persists upload and review, and isolates sample inputs', async ({ page, request }) => {
  const backup = await (await request.get('/api/system/backup')).json()
  try {
    const projects = await (await request.get('/api/projects')).json() as { id: string; display_code: string }[]
    const project = projects.find(item => item.display_code === 'P01')!
    const samples: { id: string; display_code: string }[] = []
    for (const number of [1, 2]) {
      const response = await request.post(`/api/projects/${project.id}/sample-deliveries`, { data: {
        supplier: '本地验收单位', part_display_code: `P-DETAIL-${number}`, drawing_display_code: `DETAIL-DWG-${number}`, drawing_revision: 'A', delivered_at: '2026-10-21', quantity: 1, notes: '合成样件夹具',
        drawing_parameters: [{ parameter_key: 'bore', parameter_name: '内孔直径', expected_value: 120, tolerance: 0.05, unit: 'mm', source_note: '合成图纸 120±0.05 mm' }],
      } })
      expect(response.ok(), await response.text()).toBe(true)
      samples.push(await response.json())
    }
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.goto('/')
    await openWorkspaceTab(page, '样件检验')
    const trigger = page.locator(`[data-object-id="${samples[0].id}"]`).getByRole('button', { name: '查看 / 比对', exact: true })
    await trigger.click()
    const dialog = page.getByRole('dialog', { name: `样件明细：${samples[0].display_code}`, exact: true })
    await expect(dialog.getByLabel('实测 内孔直径')).toBeVisible()
    await expect(dialog.getByRole('table', { name: '样件参数与实测', exact: true })).toBeVisible()
    await expect(dialog.getByRole('table')).toHaveCount(1)
    await dialog.getByLabel('选择样件文件').setInputFiles({ name: 'sample-proof.txt', mimeType: 'text/plain', buffer: Buffer.from('本地合成样件证据，内孔 120.02 mm。', 'utf8') })
    await dialog.getByRole('button', { name: '上传样件文件', exact: true }).click()
    await expect(dialog.getByText('样件文件已上传并记录 SHA-256')).toBeVisible()
    await dialog.getByLabel('实测 内孔直径').fill('120.02')
    await dialog.getByLabel('比对证据').fill('三坐标合成报告 DETAIL-01')
    await dialog.getByRole('button', { name: '提交比对', exact: true }).click()
    const result = dialog.getByRole('table', { name: '样件比对结果' })
    await expect(dialog.getByRole('table')).toHaveCount(1)
    await expect(result).toContainText('120.02')
    await expect(result).toContainText('mm')
    await expect(result.getByRole('row').filter({ hasText: '内孔直径' }).getByRole('cell', { name: '通过', exact: true })).toBeVisible()
    await dialog.getByRole('button', { name: '确认比对', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect(page.getByText('样件比对已确认', { exact: true })).toBeVisible()
    await expect(trigger).toBeFocused()
    await trigger.click()
    const sources = dialog.getByRole('group', { name: '登记图纸来源', exact: true })
    await sources.locator('summary').click()
    await expect(sources).toContainText('合成图纸 120±0.05 mm')
    const saved = await (await request.get(`/api/sample-deliveries/${samples[0].id}/comparison`)).json()
    expect(saved.comparison.status).toBe('confirmed')
    expect(saved.comparison.findings[0].measured_value).toBe(120.02)
    await page.screenshot({ path: `${evidence}/sample-comparison-desktop.png` })
    await page.setViewportSize({ width: 390, height: 844 })
    const bounds = await dialog.boundingBox()
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390)
    expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    await page.screenshot({ path: `${evidence}/sample-comparison-mobile.png` })
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await expect(trigger).toBeFocused()
    await page.locator(`[data-object-id="${samples[1].id}"]`).getByRole('button', { name: '查看 / 比对', exact: true }).click()
    const next = page.getByRole('dialog', { name: `样件明细：${samples[1].display_code}`, exact: true })
    await expect(next.getByLabel('实测 内孔直径')).toHaveValue('')
    await expect(next.getByLabel('比对证据')).toHaveValue('')
    expect(await next.getByLabel('选择样件文件').evaluate((element: HTMLInputElement) => element.files?.length)).toBe(0)
    await next.getByRole('button', { name: '关闭样件详情', exact: true }).click()
  } finally {
    const current = await (await request.get('/api/system/backup')).json()
    const restored = await request.post('/api/system/restore', { data: { backup, expected_state_hash: current.sha256, actor: '本地测试工程师', role: 'design_engineer' } })
    expect(restored.ok(), await restored.text()).toBe(true)
  }
})

test('conflict drawer preserves evidence and submits a real revision-checked resolution', async ({ page, request }) => {
  const backup = await (await request.get('/api/system/backup')).json()
  try {
    const projects = await (await request.get('/api/projects')).json() as { id: string; display_code: string }[]
    const project = projects.find(item => item.display_code === 'P01')!
    const requirements = await (await request.get(`/api/projects/${project.id}/requirements`)).json() as { id: string; display_code: string; current_revision: number; value_text: string }[]
    const engine = requirements.find(item => item.display_code.endsWith('B-003'))!
    const revision = await request.patch(`/api/requirements/${engine.id}`, { data: { expected_revision: engine.current_revision, value_text: String(Number(engine.value_text) + 200), source_excerpt: '本地合成变更：发动机最大扭矩增加 200 N·m' } })
    expect(revision.ok(), await revision.text()).toBe(true)
    const run = await request.post(`/api/projects/${project.id}/consistency-checks`, { data: {} })
    expect(run.ok(), await run.text()).toBe(true)
    const conflicts = await (await request.get(`/api/projects/${project.id}/conflicts`)).json() as { id: string; display_code: string; revision: number; status: string }[]
    const conflict = conflicts.find(item => item.status === 'open')!
    expect(conflict, 'the fixture must expose a real open conflict').toBeTruthy()
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.goto('/')
    await openWorkspaceTab(page, '一致性检测')
    const row = page.locator(`[data-object-id="${conflict.id}"]`)
    await expect(row.locator('details')).toHaveCount(0)
    const trigger = row.getByRole('button', { name: '查看 / 处置', exact: true })
    await trigger.click()
    const drawer = page.getByRole('dialog', { name: `冲突处置 · ${conflict.display_code}`, exact: true })
    await expect(drawer.getByRole('heading', { name: '冲突证据' })).toBeVisible()
    await drawer.getByLabel('冲突处置说明').fill('受控演示：工程师接受该风险并保留处置依据')
    await drawer.getByLabel('冲突处置证据').fill('本地验收记录，不代表产品合格')
    await drawer.getByLabel('冲突处置类型').selectOption('accepted_risk')
    await page.screenshot({ path: `${evidence}/conflict-drawer-desktop.png` })
    await page.keyboard.press('Escape')
    await expect(trigger).toBeFocused()
    await trigger.click()
    await expect(drawer.getByLabel('冲突处置证据')).toHaveValue('本地验收记录，不代表产品合格')
    await page.setViewportSize({ width: 390, height: 844 })
    expect(await drawer.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    await page.screenshot({ path: `${evidence}/conflict-drawer-mobile.png` })
    await drawer.getByRole('button', { name: '确认关闭（留痕）', exact: true }).click()
    await expect(drawer).toHaveCount(0)
    await expect(row).toBeFocused()
    await expect(row).toContainText('已关闭')
    const updated = await (await request.get(`/api/projects/${project.id}/conflicts`)).json() as { id: string; status: string; accepted_risk: boolean; evidence_text: string }[]
    expect(updated.find(item => item.id === conflict.id)).toMatchObject({ status: 'closed', accepted_risk: true, evidence_text: '本地验收记录，不代表产品合格' })
    const closedTrigger = row.getByRole('button', { name: '查看详情', exact: true })
    const writes: string[] = []
    page.on('request', request => { if (!['GET', 'HEAD', 'OPTIONS'].includes(request.method())) writes.push(request.url()) })
    await closedTrigger.click()
    const archive = page.getByRole('dialog', { name: `冲突详情 · ${conflict.display_code}`, exact: true })
    await expect(archive.getByRole('region', { name: '已保存的处置记录' })).toContainText('本地验收记录，不代表产品合格')
    await expect(archive.getByRole('region', { name: '已保存的处置记录' })).toContainText('工程师接受该风险')
    await expect(archive.getByRole('button', { name: '确认关闭（留痕）', exact: true })).toHaveCount(0)
    const history = archive.getByRole('group', { name: '冲突流转记录', exact: true })
    await history.locator('summary').click()
    await expect(history).toContainText('人工关闭')
    expect(await archive.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    await page.screenshot({ path: `${evidence}/closed-conflict-mobile.png` })
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.screenshot({ path: `${evidence}/closed-conflict-desktop.png` })
    await page.keyboard.press('Escape')
    await expect(closedTrigger).toBeFocused()
    expect(writes).toEqual([])
  } finally {
    const current = await (await request.get('/api/system/backup')).json()
    const restored = await request.post('/api/system/restore', { data: { backup, expected_state_hash: current.sha256, actor: '本地测试工程师', role: 'design_engineer' } })
    expect(restored.ok(), await restored.text()).toBe(true)
  }
})
