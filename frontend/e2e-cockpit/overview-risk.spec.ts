import { expect,test } from '@playwright/test'
const evidence=process.env.ZHIYAN_EVIDENCE_DIR??'test-results/screenshots'
test('risk summary has no inner scrollbar, opens evidence and metrics with focus return, and uses a light current stage',async({page,request})=>{
  const before=await(await request.get('/api/system/backup')).json()
  const writes:string[]=[]
  page.on('request',r=>{if(r.url().includes('/api/')&&!['GET','HEAD','OPTIONS'].includes(r.method()))writes.push(r.url())})
  await page.setViewportSize({width:1440,height:900});await page.goto('/')
  const risk=page.getByRole('region',{name:'协同风险依据'})
  await expect(risk.getByRole('listitem')).toHaveCount(1)
  const layout=await risk.locator('.risk-brief').evaluate(e=>({scroll:e.scrollHeight,visible:e.clientHeight,overflow:getComputedStyle(e.querySelector('ul')!).overflowY}))
  expect(layout.scroll).toBeLessThanOrEqual(layout.visible+1);expect(layout.overflow).toBe('visible')
  const active=page.getByRole('navigation',{name:'研发流程'}).locator("button[aria-current='step']")
  const background=await active.evaluate(e=>getComputedStyle(e).backgroundColor.match(/\d+/g)!.slice(0,3).map(Number))
  expect(Math.min(...background)).toBeGreaterThanOrEqual(210)
  await risk.screenshot({path:`${evidence}/risk-summary.png`})
  const opener=risk.getByRole('button',{name:'预警详情'});await opener.click()
  const dialog=page.getByRole('dialog',{name:'协同预警详情'})
  await expect(dialog.getByRole('heading',{name:'完整触发原因'})).toBeVisible()
  await expect(dialog.getByRole('table',{name:/原始沟通记录/})).toBeVisible()
  await page.screenshot({path:`${evidence}/risk-details.png`,fullPage:true})
  await page.keyboard.press('Escape');await expect(opener).toBeFocused()
  await risk.getByRole('button',{name:'指标说明'}).click()
  await expect(page.getByRole('dialog',{name:'协同指标说明'})).toContainText('配对样本')
  await page.keyboard.press('Escape')
  await page.setViewportSize({width:390,height:844});await opener.click()
  expect(await dialog.evaluate(e=>e.scrollWidth<=e.clientWidth+1)).toBe(true)
  await dialog.getByRole('button',{name:'关闭预警详情'}).click()
  expect(writes).toEqual([])
  expect((await(await request.get('/api/system/backup')).json()).sha256).toBe(before.sha256)
})
