import { openWorkspaceTab } from '../e2e-support/navigation'
import { expect, test } from '@playwright/test'

const evidence = process.env.ZHIYAN_EVIDENCE_DIR ?? 'test-results/screenshots'
test('calculation dialogs preserve evidence, cached results and explicit selection and analysis', async ({ page }) => {
  const errors: string[] = [], analysis: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (request.url().includes('/variant-analysis')) analysis.push(request.url()) })
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await expect(page).toHaveTitle('智研引擎 · 智能研制平台')
  await openWorkspaceTab(page, '型谱选型与变型')
  await page.getByRole('button', { name: '计算 Top-3', exact: true }).click()
  const top = page.getByRole('dialog', { name: '型谱推荐结果', exact: true })
  await expect(top.getByRole('button', { name: '选用 JX-12A', exact: true })).toBeVisible()
  await top.getByRole('group', { name: '选型输入依据', exact: true }).locator('summary').click()
  await expect(top.getByRole('group', { name: '选型输入依据', exact: true }).getByRole('row').first()).toBeVisible()
  await page.screenshot({ path: `${evidence}/top3-desktop.png` })
  await page.keyboard.press('Escape')
  const reopen = page.getByRole('button', { name: '查看推荐结果', exact: true })
  await reopen.click()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await top.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.screenshot({ path: `${evidence}/top3-mobile.png` })
  await top.getByRole('button', { name: '选用 JX-12A', exact: true }).click()
  await expect(page.getByLabel('变型分析基型编号')).toHaveValue('JX-12A')
  expect(analysis).toEqual([])
  await expect(reopen).toBeFocused()
  await page.setViewportSize({ width: 1440, height: 900 })
  const analyze = page.getByRole('button', { name: '运行变型分析', exact: true })
  await analyze.click()
  const variant = page.getByRole('dialog', { name: '变型分析结果', exact: true })
  await expect(variant.getByRole('heading', { name: '可复用件决策', exact: true })).toBeVisible()
  await expect(variant.getByRole('group', { name: '变型输入依据', exact: true })).toBeVisible()
  expect(analysis).toHaveLength(1)
  await page.screenshot({ path: `${evidence}/variant-desktop.png` })
  await page.keyboard.press('Escape')
  await expect(analyze).toBeFocused()
  await page.getByRole('button', { name: '查看变型结果', exact: true }).click()
  expect(analysis).toHaveLength(1)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await variant.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await expect(variant.getByText('左右滑动表格查看全部参数、依据与来源。')).toBeVisible()
  await page.screenshot({ path: `${evidence}/variant-mobile.png` })
  await variant.getByRole('button', { name: '关闭变型结果', exact: true }).click()
  await page.setViewportSize({ width: 1440, height: 900 })
  await openWorkspaceTab(page, '设计成果')
  await page.getByRole('button', { name: '重新计算相似项目', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '相似项目匹配结果', exact: true }).locator('.card').first()).toBeVisible()
  await page.keyboard.press('Escape')
  const similarTrigger = page.getByRole('button', { name: '查看相似项目', exact: true })
  await similarTrigger.click()
  const similar = page.getByRole('dialog', { name: '相似项目匹配结果', exact: true })
  await expect(similar.locator('.card').first()).toBeVisible()
  await page.screenshot({ path: `${evidence}/similar-desktop.png` })
  await page.keyboard.press('Escape')
  await expect(similarTrigger).toBeFocused()
  await page.getByRole('button', { name: '重新计算相似项目', exact: true }).click()
  await expect(similar.locator('.card').first()).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await similar.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.screenshot({ path: `${evidence}/similar-mobile.png` })
  await similar.getByRole('button', { name: '关闭相似项目', exact: true }).click()
  expect(errors).toEqual([])
})
