import { openWorkspaceTab } from '../e2e-support/navigation'
import { expect, test, type APIRequestContext } from '@playwright/test'

const evidence = process.env.ZHIYAN_EVIDENCE_DIR ?? 'test-results/screenshots'
async function restore(request: APIRequestContext, backup: unknown) {
  const current = await (await request.get('/api/system/backup')).json()
  const response = await request.post('/api/system/restore', { data: { backup, expected_state_hash: current.sha256, actor: '本地测试工程师', role: 'design_engineer' } })
  expect(response.ok(), await response.text()).toBe(true)
}

test('issue drawer retains evidence on failure and saves close and reopen without moving the list', async ({ page, request }) => {
  const backup = await (await request.get('/api/system/backup')).json()
  try {
    const projects: { id: string; display_code: string }[] = await (await request.get('/api/projects')).json()
    const project = projects.find(item => item.display_code === 'P01')!
    const source = await request.post(`/api/projects/${project.id}/source-documents`, { data: { display_code: 'UI-T-PROTOCOL', doc_type: 'protocol', version: 'V1', content: '3.1 发动机最大扭矩 2600 N·m。\n9.1 耐久按双方商定标准执行。', mode: 'manual' } })
    expect(source.ok(), await source.text()).toBe(true)
    const document = await source.json()
    const parsed = await request.post(`/api/source-documents/${document.id}/parse`, { data: { display_code_map: {} } })
    expect(parsed.ok(), await parsed.text()).toBe(true)
    const issues: { id: string; source_document_id: string; status: string; source_excerpt: string }[] = await (await request.get(`/api/projects/${project.id}/issues`)).json()
    const issue = issues.find(item => item.source_document_id === document.id && item.status === 'open' && item.source_excerpt)!
    expect(issue).toBeTruthy()
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.goto('/')
    await openWorkspaceTab(page, '协议解析与澄清')
    const row = page.locator(`[data-object-id="${issue.id}"]`)
    const trigger = row.getByRole('button', { name: '关闭', exact: true })
    await trigger.click()
    const drawer = page.getByRole('dialog', { name: '问题处置', exact: true })
    expect(await drawer.evaluate(element => element.matches(':modal'))).toBe(true)
    await expect(drawer.getByRole('region', { name: '问题来源与证据' })).toContainText(issue.source_excerpt)
    await drawer.getByLabel('问题处置类型').selectOption('accepted_risk')
    await drawer.getByLabel('问题处置说明').fill('本地夹具：保留问题风险并跟踪补录')
    await drawer.getByLabel('问题处置证据').fill('UI-T-ISSUE：合成评审记录')
    await page.screenshot({ path: `${evidence}/issue-drawer-desktop.png` })
    await page.keyboard.press('Escape')
    await expect(trigger).toBeFocused()
    const notChanged = await (await request.get(`/api/issues/${issue.id}`)).json()
    expect(notChanged.status).toBe('open')
    await trigger.click()
    await expect(drawer.getByLabel('问题处置证据')).toHaveValue('UI-T-ISSUE：合成评审记录')
    let release!: () => void
    const hold = new Promise<void>(resolve => { release = resolve })
    await page.route(`**/api/issues/${issue.id}/close`, async route => {
      await hold
      await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { message: '模拟保存失败，输入保留' } }) })
    }, { times: 1 })
    await drawer.getByRole('button', { name: '确认关闭', exact: true }).click()
    await expect(drawer.getByRole('button', { name: '关闭问题详情' })).toBeDisabled()
    await page.keyboard.press('Escape')
    await expect(drawer).toBeVisible()
    release()
    await expect(drawer.getByRole('alert')).toContainText('模拟保存失败')
    await expect(drawer.getByLabel('问题处置说明')).toHaveValue('本地夹具：保留问题风险并跟踪补录')
    await page.setViewportSize({ width: 390, height: 844 })
    expect(await drawer.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    await page.screenshot({ path: `${evidence}/issue-drawer-mobile.png` })
    await drawer.getByRole('button', { name: '确认关闭', exact: true }).click()
    await expect(drawer).toHaveCount(0)
    await expect(row).toContainText('已关闭')
    await expect(row.getByRole('button', { name: '重开', exact: true })).toBeFocused()
    const closed = await (await request.get(`/api/issues/${issue.id}`)).json()
    expect(closed.status).toBe('closed')
    expect(closed.close_reason).toContain('本地夹具')
    await row.getByRole('button', { name: '重开', exact: true }).click()
    await drawer.getByLabel('问题重开原因').fill('补充来源后再次复核')
    await drawer.getByRole('button', { name: '确认重开', exact: true }).click()
    await expect(drawer).toHaveCount(0)
    await expect(row.getByRole('button', { name: '关闭', exact: true })).toBeFocused()
    expect((await (await request.get(`/api/issues/${issue.id}`)).json()).status).toBe('open')
  } finally { await restore(request, backup) }
})

test('communication drawer shows saved records, imports with retry and isolates the next topic', async ({ page, request }) => {
  const backup = await (await request.get('/api/system/backup')).json()
  try {
    const projects: { id: string; display_code: string }[] = await (await request.get('/api/projects')).json()
    const project = projects.find(item => item.display_code === 'P01')!
    const topics: { id: string; display_code: string }[] = []
    for (const name of ['接口复核：抽屉验收', '样件交付：抽屉验收']) {
      const response = await request.post(`/api/projects/${project.id}/coordination-topics`, { data: { name, expected_participants: ['设计部', '试验部'], window_start: '2026-10-21T00:00:00Z', window_end: '2026-10-23T00:00:00Z' } })
      expect(response.ok(), await response.text()).toBe(true)
      topics.push(await response.json())
    }
    const initial = await request.post(`/api/coordination-topics/${topics[0].id}/records`, { data: { external_id: 'UI-T-MSG-001', record_type: 'message', sender: '设计部', content_summary: '请核对接口数据（本地合成）', sent_at: '2026-10-22T01:00:00Z', reply_to_external_id: null } })
    expect(initial.ok(), await initial.text()).toBe(true)
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.goto('/')
    await openWorkspaceTab(page, '协同风险')
    const topic = page.getByRole('article', { name: `协同议题 ${topics[0].display_code}`, exact: true })
    const view = topic.getByRole('button', { name: '查看沟通记录', exact: true })
    await view.click()
    const drawer = page.getByRole('dialog', { name: `议题沟通记录 · ${topics[0].display_code}`, exact: true })
    await expect(drawer.getByText('UI-T-MSG-001', { exact: true })).toBeVisible()
    await expect(drawer.getByRole('button', { name: '关闭沟通详情' })).toBeFocused()
    await page.keyboard.press('Shift+Tab')
    expect(await drawer.evaluate(element => element.contains(document.activeElement))).toBe(true)
    await page.screenshot({ path: `${evidence}/communication-drawer-desktop.png` })
    await page.keyboard.press('Escape')
    await expect(view).toBeFocused()
    const importing = topic.getByRole('button', { name: '导入沟通记录', exact: true })
    await importing.click()
    await expect(drawer.getByLabel('协同记录外部编号')).toBeFocused()
    await drawer.getByLabel('协同记录外部编号').fill('UI-T-MSG-002')
    await drawer.getByLabel('协同记录发送方').fill('试验部')
    await drawer.getByLabel('协同记录发送时间').fill('2026-10-22T10:30')
    await drawer.getByLabel('协同记录摘要').fill('接口数据已回复（本地合成）')
    await drawer.getByLabel('协同记录响应对象').fill('UI-T-MSG-001')
    await page.keyboard.press('Escape')
    await expect(importing).toBeFocused()
    const before = await (await request.get(`/api/coordination-topics/${topics[0].id}`)).json()
    expect(before.records).toHaveLength(1)
    await importing.click()
    await expect(drawer.getByLabel('协同记录外部编号')).toHaveValue('UI-T-MSG-002')
    await page.route(`**/api/coordination-topics/${topics[0].id}/records`, route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { message: '模拟导入失败' } }) }), { times: 1 })
    await drawer.getByRole('button', { name: '导入记录', exact: true }).click()
    await expect(drawer.getByRole('alert')).toContainText('模拟导入失败')
    await expect(drawer.getByLabel('协同记录摘要')).toHaveValue('接口数据已回复（本地合成）')
    await drawer.getByRole('button', { name: '导入记录', exact: true }).click()
    await expect(drawer.getByText('协同记录已导入', { exact: true })).toBeVisible()
    await expect(drawer.getByText('UI-T-MSG-002', { exact: true })).toBeVisible()
    const after = await (await request.get(`/api/coordination-topics/${topics[0].id}`)).json()
    expect(after.records).toHaveLength(2)
    expect(after.records.find((record: { external_id: string }) => record.external_id === 'UI-T-MSG-002')).toMatchObject({ sender: '试验部', reply_to_external_id: 'UI-T-MSG-001' })
    await page.setViewportSize({ width: 390, height: 844 })
    expect(await drawer.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    await page.screenshot({ path: `${evidence}/communication-drawer-mobile.png` })
    await drawer.getByRole('button', { name: '关闭沟通详情' }).click()
    await expect(importing).toBeFocused()
    await page.getByRole('article', { name: `协同议题 ${topics[1].display_code}`, exact: true }).getByRole('button', { name: '导入沟通记录', exact: true }).click()
    const next = page.getByRole('dialog', { name: `议题沟通记录 · ${topics[1].display_code}`, exact: true })
    await expect(next.getByLabel('协同记录发送方')).toHaveValue('')
    await expect(next.getByLabel('协同记录外部编号')).toHaveValue('')
    await expect(next.getByText('暂无记录。', { exact: true })).toBeVisible()
    await next.getByRole('button', { name: '关闭沟通详情' }).click()
  } finally { await restore(request, backup) }
})
