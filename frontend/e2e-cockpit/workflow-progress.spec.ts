import { test,expect } from '@playwright/test'
import { openWorkspaceTab } from '../e2e-support/navigation'
const evidence=process.env.ZHIYAN_EVIDENCE_DIR??'test-results/screenshots'
test('workflow views show real test/sample state and version comparison',async({page,request})=>{
 await page.goto('/')
 const project=(await(await request.get('/api/projects')).json())[0]
 const summary=await(await request.get(`/api/projects/${project.id}/workflow-summary`)).json()
 await openWorkspaceTab(page,'试验验证与追溯')
 const testing=page.getByRole('region',{name:'试验状态与进度'})
 await expect(testing).toContainText(`${summary.testing.total} 个用例`)
 await expect(testing.getByLabel('当前通过',{exact:true})).toContainText(String(summary.testing.execution.pass))
 await page.screenshot({path:`${evidence}/testing-progress.png`,fullPage:true})
 await openWorkspaceTab(page,'样件检验')
 const samples=page.getByRole('region',{name:'样件检验流程'})
 await expect(samples).toContainText('图纸基准')
 await expect(samples).toContainText('审核确认')
 await page.screenshot({path:`${evidence}/sample-process.png`,fullPage:true})
 await openWorkspaceTab(page,'一致性检测')
 await expect(page.getByRole('region',{name:'参数与版本变化'})).toContainText('样件图纸基准与实测')
 await page.screenshot({path:`${evidence}/consistency-comparisons.png`,fullPage:true})
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:`${evidence}/consistency-mobile.png`,fullPage:true})
})
test('participant progress creates grounded alerts and stales the metric after revision',async({page,request})=>{
 const backup=await(await request.get('/api/system/backup')).json()
 try{
 const project=(await(await request.get('/api/projects')).json())[0]
 const topicResponse=await request.post(`/api/projects/${project.id}/coordination-topics`,{data:{name:'AB进度验收',expected_participants:['A','B'],window_start:'2026-10-20T00:00:00Z',window_end:'2026-10-24T00:00:00Z'}})
 expect(topicResponse.ok()).toBe(true)
 const topic=await topicResponse.json()
 await page.goto('/');await openWorkspaceTab(page,'协同风险')
 const card=page.getByRole('article',{name:`协同议题 ${topic.display_code}`,exact:true})
 async function report(participant:string,actual:string,version:string){
 await card.getByRole('button',{name:'登记参与方进度'}).click()
 const dialog=page.getByRole('dialog',{name:'参与方进度登记'})
 await dialog.getByLabel('进度参与方').selectOption(participant)
 await dialog.getByLabel('进度里程碑').fill('设计冻结')
 await dialog.getByLabel('计划进度百分比').fill('80')
 await dialog.getByLabel('实际进度百分比').fill(actual)
 await dialog.getByLabel('交付版本',{exact:true}).fill(version)
 await dialog.getByLabel('进度记录时间').fill('2026-10-23T16:00')
 await dialog.getByLabel('进度依据').fill(`${participant}方合成周报`)
 await dialog.getByRole('button',{name:'保存参与方进度'}).click()
 await expect(dialog).toHaveCount(0)
 }
 await report('A','90','V2');await report('B','30','V1')
 await expect(card.getByText('A 90% / B 30%，进度相差60个百分点',{exact:true})).toBeVisible()
 await expect(card).toContainText('交付版本不一致：A V2 / B V1')
 await card.getByRole('button',{name:'重算指标',exact:true}).click()
 let metrics=await(await request.get(`/api/coordination-topics/${topic.id}/metrics`)).json()
 expect(metrics.metric_run.risk.risk_level).toBe('high')
 expect(metrics.metric_run.validity).toBe('current')
 await page.screenshot({path:`${evidence}/coordination-progress-alerts.png`,fullPage:true})
 await report('B','70','V2')
 await expect(card).toContainText('指标待重算')
 metrics=await(await request.get(`/api/coordination-topics/${topic.id}/metrics`)).json()
 expect(metrics.metric_run.validity).toBe('stale')
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await card.getByRole('button',{name:'登记参与方进度'}).click()
 expect(await page.getByRole('dialog',{name:'参与方进度登记'}).evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true)
 await page.screenshot({path:`${evidence}/progress-registration-mobile.png`,fullPage:true})
 }finally{
 const current=await(await request.get('/api/system/backup')).json()
 const restored=await request.post('/api/system/restore',{data:{backup,expected_state_hash:current.sha256,actor:'本地测试工程师',role:'design_engineer'}})
 expect(restored.ok(),await restored.text()).toBe(true)
 }
})
