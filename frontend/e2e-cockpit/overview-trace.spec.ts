import { expect, test } from '@playwright/test'
const evidence = process.env.ZHIYAN_EVIDENCE_DIR ?? 'test-results/screenshots'

test('overview trace links open versioned evidence and restore focus without writing business data', async ({page, request}) => {
  const before = await (await request.get('/api/system/backup')).json()
  await page.setViewportSize({width:1920,height:1080})
  await page.goto('/')
  const trace = page.getByRole('region',{name:'当前验证追溯'})
  await expect(trace.getByRole('table')).toHaveAccessibleName('需求设计试验追溯表')
  await expect(trace.getByRole('columnheader',{name:'设计评审项'})).toBeVisible()
  await expect(trace.getByText(/DR-01/)).toBeVisible()
  await expect(trace.getByText(/TC-007/)).toBeVisible()
  await expect(trace.getByRole('img',{name:/有效用例覆盖率/})).toBeVisible()
  await page.screenshot({path:`${evidence}/trace-dashboard.png`,fullPage:true})
  const view = trace.getByRole('button',{name:'查看变速器最低额定输入扭矩追溯详情'})
  await view.click()
  const dialog = page.getByRole('dialog',{name:'变速器最低额定输入扭矩 · 追溯详情'})
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('heading',{name:'设计评审依据'})).toBeVisible()
  const linkedReviews = dialog.getByText(/评审 V1 · 引用需求 V1/)
  expect(await linkedReviews.count()).toBeGreaterThanOrEqual(1)
  for (const review of await linkedReviews.all()) await expect(review).toBeVisible()
  await expect(dialog.getByRole('heading',{name:/TC-007/})).toBeVisible()
  await expect(dialog.getByText('通过准则',{exact:true})).toBeVisible()
  await page.screenshot({path:`${evidence}/trace-dialog.png`,fullPage:true})
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(view).toBeFocused()
  await page.setViewportSize({width:390,height:844})
  await view.click()
  await expect(dialog).toBeVisible()
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
  await dialog.getByRole('button',{name:'关闭追溯详情'}).click()
  expect((await (await request.get('/api/system/backup')).json()).sha256).toBe(before.sha256)
})
